func TestGenerateRandomElements(t *testing.T) {
	options := map[string][]interface{}{
		"irregular_empty":    {0, nil},
		"regular_medium":     {1000, 1000},
		"irregular_negative": {-7, nil},
		"regular_small":      {4, 4},
		"regular_large":      {10000000, 10000000},
	}

	for name, option := range options {
		t.Run(name, func(t *testing.T) {
			size := option[0].(int)
			result := generateRandomElements(size)
			switch ans := option[1].(type) {
			case nil:
				if result != nil {
					t.Errorf("get %v != want %v", result, nil)
				}
			case int:
				if len(result) != ans {
					t.Errorf("get %d != want %d", len(result), ans)
				}
			}
		})
	}
}

